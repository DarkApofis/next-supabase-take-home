// Regenerates supabase/seed.sql from the CSV. Run: pnpm seed:generate
import { readFileSync, writeFileSync } from "node:fs";
import { parseCsv, toInsertStatements } from "../domain/coffee-records/csv.ts";

const source = "data/synthetic_coffee_health_10000.csv";
const target = "supabase/seed.sql";

const rows = parseCsv(readFileSync(source, "utf8"));
const header = `-- Generated by \`pnpm seed:generate\` from ${source} (${rows.length} rows). Do not edit.\n`;
writeFileSync(target, header + toInsertStatements(rows));
console.log(`Wrote ${rows.length} rows to ${target}`);
